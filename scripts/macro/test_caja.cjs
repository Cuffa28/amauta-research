const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const model = require('../../public/macro-lab/caja-model.js');
const data = JSON.parse(fs.readFileSync(path.join(__dirname,'../../public/macro-lab/live/caja-2027.json'),'utf8'));
assert.equal(data.mensual_2027.length,12);
assert.equal(new Set(data.mensual_2027.map(m=>m.mes)).size,12);
const total=data.mensual_2027.reduce((n,m)=>n+m.servicio_usd_equivalente_millones,0);
assert.ok(Math.abs(total-27911.491185305887)<1e-6);
assert.ok(data.mensual_2027.every(m=>m.brecha_caja_usd_millones===null));
assert.equal(model.calculate(null,[{inflows:100,payments:10}])[0].closing,null);
assert.deepEqual(model.calculate(50,[{inflows:0,payments:70},{inflows:40,payments:10}]).map(m=>m.closing),[-20,10]);
assert.deepEqual(model.calculate(50,[{inflows:null,payments:10},{inflows:100,payments:10}]).map(m=>m.closing),[null,null]);
assert.equal(model.calculate(50,[{inflows:NaN,payments:10}])[0].closing,null);
assert.equal(model.confirmed(data.fundingLedger,'2027-01'),0);
assert.ok(data.fundingLedger.every(r=>!model.eligible(r)));
const firm={issuer:'Tesoro',status:'unconditional',currency:'USD',month:'2027-03',netAmount:100,freeAvailability:true,sourceUrl:'https://example.org/contract',evidenceDate:'2026-11-17'};
assert.equal(model.confirmed([firm],'2027-03'),100);
assert.equal(model.confirmed([firm],'2027-04'),0);
for(const change of [{status:'conditional'},{issuer:'BCRA'},{currency:'ARS'},{freeAvailability:false},{month:null},{netAmount:null},{sourceUrl:''},{evidenceDate:''}])assert.equal(model.eligible({...firm,...change}),false);
console.log('Caja 2027: totales, datos faltantes, propagación de saldos y elegibilidad verificados.');
